import { typescript, javascript } from '@frsource/eslint-config';
import { createConfigForNuxt } from '@nuxt/eslint-config/flat';
import prettier from 'eslint-config-prettier';
import vue from 'eslint-plugin-vue';
import tseslint from 'typescript-eslint';
import globals from 'globals';

// @nuxt/eslint-config is a whole-project preset; scope every entry of it to apps/site
const scopeToSite = (config) => ({
  ...config,
  files: config.files
    ? config.files.map((f) => (typeof f === 'string' ? `apps/site/${f}` : f))
    : ['apps/site/**'],
});
const nuxt = (
  await createConfigForNuxt({
    features: { tooling: false, stylistic: false },
  })
).map(scopeToSite);

/** @type {import("eslint").Linter.Config[]} */
export default [
  {
    ignores: [
      '**/dist',
      '**/coverage',
      '**/node_modules',
      '**/.nuxt',
      '**/.output',
      '**/.data',
      '**/*.d.ts',
      // generated by apps/site/scripts/sync-*.mjs
      'apps/site/public/schema',
    ],
  },
  // the packages; apps/site gets the Nuxt preset below
  ...[...javascript, ...typescript].map((config) => ({
    ...config,
    ignores: [...(config.ignores ?? []), 'apps/site/**'],
  })),
  ...vue.configs['flat/recommended'].map((config) => ({
    ...config,
    files: ['**/*.vue'],
    ignores: [...(config.ignores ?? []), 'apps/site/**'],
  })),
  ...nuxt,
  {
    files: ['**/*.vue'],
    plugins: { '@typescript-eslint': tseslint.plugin },
    languageOptions: { parserOptions: { parser: tseslint.parser } },
    // the base rule can't see type-only usage in <script lang="ts">
    rules: {
      'no-unused-vars': 'off',
      '@typescript-eslint/no-unused-vars': 'error',
    },
  },
  // Nuxt auto-imports (useRoute, ...) are invisible to eslint; TypeScript reports undefined names
  { files: ['apps/site/**', '**/*.vue'], rules: { 'no-undef': 'off' } },
  // formatting is prettier's job, keep it last among the rule sets
  prettier,
  { rules: { '@typescript-eslint/no-invalid-void-type': 'off' } },
  {
    files: [
      'packages/*/src/**',
      'packages/*/scripts/**',
      'scripts/**',
      'apps/site/scripts/**',
      '.claude/skills/*/scripts/**',
      'examples/**',
    ],
    languageOptions: {
      globals: {
        ...globals.es2021,
        ...globals.node,
      },
    },
  },
  {
    files: ['packages/*/app/**'],
    languageOptions: { globals: { ...globals.browser } },
  },
  // verification scripts and the converter examples report through stdout
  {
    files: ['.claude/skills/*/scripts/**', 'examples/**'],
    rules: { 'no-console': 'off' },
  },
  // Jest runs CommonJS unless told otherwise, which is how jest-image-snapshot is used
  {
    files: ['examples/converters/jest-image-snapshot/tests/**'],
    languageOptions: { globals: { ...globals.jest } },
    rules: { '@typescript-eslint/no-require-imports': 'off' },
  },
  // the viewer is a command line tool: printing is its interface
  {
    files: ['packages/visual-regression-viewer/src/{cli,main}.ts'],
    rules: { 'no-console': 'off' },
  },
];
